"""Build Press/Gantry casings and workstation attachments from shared mount coordinates."""
import json,math,subprocess,tempfile
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
ASSETS=ROOT/'src/main/resources/assets/vandorlabs'
MODELS=ASSETS/'models/block'
SHELLS=json.loads((ROOT/'tools/assets/builder_shells.json').read_text())
def presentation():
    java=Path('/usr/lib/jvm/java-8-openjdk-amd64/bin')
    with tempfile.TemporaryDirectory(prefix='builder-presentation-') as out:
        subprocess.run([str(java/'javac'),'-encoding','UTF-8','-d',out,'-sourcepath',str(ROOT/'src/portable/java'),str(ROOT/'tools/java/BuilderPresentationExport.java')],check=True)
        return json.loads(subprocess.check_output([str(java/'java'),'-cp',out,'BuilderPresentationExport'],text=True))
def cuts(lo,hi,period=1):return sorted({lo,hi,*[n*period for n in range(math.ceil(lo/period),math.ceil(hi/period)) if lo<n*period<hi]})
def generate(id,s):
    lines=['# Generated by tools/generate_builder_attachments.py','mtllib materials.mtl'];materials={};nv=nt=0;surfaces=[]
    def mat(name,texture):materials[name]=texture;return name
    casing=mat('builder_casing','vandorlabs:blocks/universal_constructor/synthesis_casing')
    interior=mat('builder_interior','vandorlabs:blocks/frames/frames-door-window/door_interior_dark_rail')
    glass=mat('atlas','vandorlabs:blocks/universal_constructor/'+id)
    bezel=mat('builder_bezel','vandorlabs:blocks/resource_ports/port_hull')
    black=mat('builder_screen','minecraft:blocks/concrete_black')
    keys=mat('builder_keys','vandorlabs:blocks/universal_constructor/synthesis_keyboard')
    def quad(group,material,points,uv=((0,1),(1,1),(1,0),(0,0))):
        nonlocal nv,nt
        surfaces.append((group,material,points,uv))
        lines.extend(['g '+group,'usemtl '+material])
        lines.extend('v %.8f %.8f %.8f'%tuple(p) for p in points)
        lines.extend('vt %.8f %.8f'%tuple(t) for t in uv)
        lines.append('f '+' '.join('%d/%d'%(nv+i,nt+i) for i in range(1,5)));nv+=4;nt+=4
    def panel(group,material,points):
        # Split axis-aligned authored faces at block boundaries. Every UV unit
        # retains one block of material instead of stretching an atlas over a wall.
        axis=next(a for a in range(3) if max(p[a] for p in points)-min(p[a] for p in points)<1e-8)
        u,v=([2,1] if axis==0 else [0,2] if axis==1 else [0,1]);base=points[0][axis]
        lo=[min(p[a] for p in points) for a in range(3)];hi=[max(p[a] for p in points) for a in range(3)]
        us,vs=cuts(lo[u],hi[u]),cuts(lo[v],hi[v])
        # Preserve winding exactly, including the original glass-facing normals.
        orientation=[(1 if p[u]>lo[u]+1e-8 else 0,1 if p[v]>lo[v]+1e-8 else 0) for p in points]
        for a,b in zip(us,us[1:]):
            for c,d in zip(vs,vs[1:]):
                # Frame artwork is one native panel per block. The continuous
                # grey interior texture repeats twice per block, never stretches
                # over a whole wall, and never samples outside its atlas sprite.
                tile_material=interior if material==casing and (b-a<1-1e-8 or d-c<1-1e-8) else material
                period=.5 if tile_material==interior else 1
                aa,cc=cuts(a,b,period),cuts(c,d,period)
                for A,B in zip(aa,aa[1:]):
                    for C,D in zip(cc,cc[1:]):
                        pts=[];uv=[]
                        for iu,iv in orientation:
                            p=[0,0,0];p[axis]=base;p[u]=B if iu else A;p[v]=D if iv else C;pts.append(p)
                            uv.append(((p[u]-math.floor(A/period)*period)/period,(p[v]-math.floor(C/period)*period)/period))
                        quad(group,tile_material,pts,uv)
    def box(group,material,x,y,z,X,Y,Z,skip=()):
        faces={'north':[(x,Y,z),(X,Y,z),(X,y,z),(x,y,z)],'south':[(X,Y,Z),(x,Y,Z),(x,y,Z),(X,y,Z)],'west':[(x,Y,Z),(x,Y,z),(x,y,z),(x,y,Z)],'east':[(X,Y,z),(X,Y,Z),(X,y,Z),(X,y,z)],'up':[(x,Y,z),(x,Y,Z),(X,Y,Z),(X,Y,z)],'down':[(x,y,Z),(x,y,z),(X,y,z),(X,y,Z)]}
        for name,pts in faces.items():
            if name not in skip:panel(group+'_'+name,material,pts)
    retired={'static__closed_plinth','static__main_chassis','static__console_shelf','static__screen_housing'}
    for face in SHELLS[id]:
        g=face['group'];points=[v[:3] for v in face['vertices']]
        if g in retired or g.startswith('press__'):continue
        if id=='enclosed_gantry':
            if g.startswith('head__'):
                # Half-size unit, attached at the new upper rail, with its
                # bottom-center laser outlet at (2.5, 3.25, 1.21875).
                points=[(2.5+(x-2.5)*.5,3.75+(y-2.8125)*.5,1.21875+(z-1.21875)*.5) for x,y,z in points]
                g='gantry_head'
            elif g=='static__overhead_beam':
                points=[(x,y+1,z) for x,y,z in points];g='gantry_arm'
            elif g in ('static__left_support','static__right_support'):
                points=[(x,y if y<=1 else 1+(y-1)*1.5,z) for x,y,z in points]
            elif g.startswith('glass__'):
                points=[(x,y+1 if y>2 else y,z) for x,y,z in points]
        if g.startswith('glass__'):quad(g,glass,points,[v[3:] for v in face['vertices']])
        else:panel(g,interior if g in ('gantry_head','gantry_arm','static__build_bed') else casing,points)
    if id=='assembly_press':
        emitter=mat('press_emitter','minecraft:blocks/concrete_green')
        for i,(x,z) in enumerate(((1.125,.4375),(3.125,.4375),(1.125,2.5),(3.125,2.5))):
            box('static__laser_housing_'+str(i),interior,x-.0625,2.4375,z-.0625,x+.0625,2.625,z+.0625,skip=('down',))
            quad('static__laser_aperture_'+str(i),emitter,[(x-.03125,2.4375,z+.03125),(x-.03125,2.4375,z-.03125),(x+.03125,2.4375,z-.03125),(x+.03125,2.4375,z+.03125)])
    w=int(s['width']);depth=int(s['depth'])
    # Replace the old stretched plinth. The flush rack owns its entire front,
    # side and underside region; ports own their bottom-corner faces.
    for x in range(w):
        if x!=0:quad('static__base_front',casing,[(x,1,0),(x+1,1,0),(x+1,0,0),(x,0,0)])
        if x not in (0,w-1):quad('static__base_rear',casing,[(x+1,1,depth),(x,1,depth),(x,0,depth),(x+1,0,depth)])
        for z in range(depth):
            if not(x==0 and z==0) and not(z==depth-1 and x in (0,w-1)):panel('static__base_bottom',casing,[(x,0,z+1),(x,0,z),(x+1,0,z),(x+1,0,z+1)])
            if not(x==0 and z==0):panel('static__base_top',casing,[(x,1,z),(x,1,z+1),(x+1,1,z+1),(x+1,1,z)])
    for z in range(depth):
        if z not in (0,depth-1):panel('static__base_left',casing,[(0,1,z+1),(0,1,z),(0,0,z),(0,0,z+1)])
        panel('static__base_right',casing,[(w,1,z),(w,1,z+1),(w,0,z+1),(w,0,z)])
    def front(group,material,x,y,size,z):quad(group,material,[(x-size/2,y+size/2,z),(x+size/2,y+size/2,z),(x+size/2,y-size/2,z),(x-size/2,y-size/2,z)])
    # A shallow dedicated housing carries the screen on the left front pillar.
    sx,sy,sz=s['screenX'],s['screenY'],s['screenZ'];half=s['screenFrame']/2
    box('static__display_housing',interior,sx-half,sy-half,sz+.01,sx+half,sy+half,.375,skip=('north',))
    front('static__display_bezel',bezel,sx,sy,s['screenFrame'],sz+.005)
    front('static__display',black,sx,sy,s['screenSize'],sz)
    x,y,z=s['keyboardX'],s['keyboardY'],s['keyboardZ'];kw,kd=s['keyboardWidth'],s['keyboardDepth']
    box('static__keyboard_case',interior,x,y-.125,z,x+kw,y,z+kd,skip=('up',))
    quad('static__keyboard',keys,[(x,y,z),(x,y,z+kd),(x+kw,y,z+kd),(x+kw,y,z)],((0,.5),(0,1),(1,1),(1,.5)))
    # Vanilla EnumFaceDirection vertex order; UVs below use BlockFaceUV vertex0..3.
    faces={'north':(2,1,0,3),'south':(7,4,5,6),'west':(3,0,4,7),'east':(6,5,1,2),'up':(3,7,6,2),'down':(4,0,1,5)}
    for label,path,ox,oy,oz,north in [('rack','module_rack/shell.json',s['rackX'],s['rackY'],s['rackZ'],True),('chip','token_slots/data_chip_slot_north_0.json',s['chipX']-.5,s['chipY']-.5,s['chipZ']-.975,False)]:
        model=json.loads((MODELS/path).read_text())
        for key,texture in model['textures'].items():mat(label+'_'+key,texture)
        for index,e in enumerate(model['elements']):
            x,y,z=[v/16 for v in e['from']];X,Y,Z=[v/16 for v in e['to']];p=[(x,y,z),(X,y,z),(X,Y,z),(x,Y,z),(x,y,Z),(X,y,Z),(X,Y,Z),(x,Y,Z)]
            default={'down':[x*16,16-Z*16,X*16,16-z*16],'up':[x*16,z*16,X*16,Z*16],'north':[16-X*16,16-Y*16,16-x*16,16-y*16],'south':[x*16,16-Y*16,X*16,16-y*16],'west':[z*16,16-Y*16,Z*16,16-y*16],'east':[16-Z*16,16-Y*16,16-z*16,16-y*16]}
            for side,f in e['faces'].items():
                pts=[]
                for i in faces[side]:
                    px,py,pz=p[i]
                    if north:px,pz=1-px,1-pz
                    pts.append((ox+px,oy+py,oz+pz))
                a,b,c,d=f.get('uv',default[side]);quad('static__'+label+'_'+str(index)+'_'+side,label+'_'+f['texture'][1:],pts,((a/16,1-b/16),(a/16,1-d/16),(c/16,1-d/16),(c/16,1-b/16)))
    for name,pts in [('power_in_off',[(w-1,0,depth),(w,0,depth),(w,1,depth),(w-1,1,depth)]),('power_in_off',[(w-1,0,depth-1),(w,0,depth-1),(w,0,depth),(w-1,0,depth)]),('matter_in_off',[(0,0,depth),(1,0,depth),(1,1,depth),(0,1,depth)]),('matter_out_off',[(0,0,depth-1),(1,0,depth-1),(1,0,depth),(0,0,depth)]),('matter_out_off',[(0,0,depth-1),(0,0,depth),(0,1,depth),(0,1,depth-1)])]:
        material=mat('port_'+name,'vandorlabs:blocks/resource_ports/'+name);quad('static__port_'+name,material,pts)
    target=MODELS/'universal_constructor'/id
    (target/'complete.obj').write_text('\n'.join(lines)+'\n')
    if id=='enclosed_gantry':
        def export(name,predicate):
            result=['# Generated moving gantry assembly','mtllib materials.mtl'];n=0
            for group,material,points,uv in surfaces:
                if not predicate(group):continue
                result.extend(['g '+group,'usemtl '+material]);result.extend('v %.8f %.8f %.8f'%tuple(p) for p in points);result.extend('vt %.8f %.8f'%tuple(t) for t in uv);result.append('f '+' '.join('%d/%d'%(n+i,n+i) for i in range(1,5)));n+=4
            (target/name).write_text('\n'.join(result)+'\n')
        export('static.obj',lambda group:group not in ('gantry_arm','gantry_head'))
        export('gantry_arm.obj',lambda group:group=='gantry_arm')
        export('gantry_head.obj',lambda group:group=='gantry_head')

    (target/'materials.mtl').write_text('\n'.join('newmtl '+name+'\nKa 1 1 1\nKd 1 1 1\nd 1\nillum 1\nmap_Kd '+texture+'\n' for name,texture in materials.items()))
def main():
    specs=presentation()
    for id,s in specs.items():generate(id,s)
    path=ASSETS/'data/frame_machines.json';catalog=json.loads(path.read_text())
    for design in catalog:
        if design['design'] in specs:
            s=specs[design['design']];design['height']=4 if design['design']=='enclosed_gantry' else 3;design['chip_anchor']=[s['chipX'],s['chipY'],s['chipZ']];design['chip_size']=[6,6];design['state_models']=['complete.obj']*3
    path.write_text(json.dumps(catalog,indent=2)+'\n')
if __name__=='__main__':main()
