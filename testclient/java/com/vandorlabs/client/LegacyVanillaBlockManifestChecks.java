package com.vandorlabs.client;

import net.minecraft.block.Block;
import net.minecraft.util.ResourceLocation;
import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;

/** Export only the actual vanilla registry: modded numeric assignments are not portable. */
public final class LegacyVanillaBlockManifestChecks {
    public static void main(String[] args)throws Exception {
        net.minecraft.init.Bootstrap.register();
        TreeMap<Integer,String> names=new TreeMap<>();
        for(Block block:Block.REGISTRY){
            ResourceLocation name=block.getRegistryName();
            if(name!=null&&"minecraft".equals(name.getResourceDomain())){
                int id=Block.getIdFromBlock(block);
                if(id<0||id>255||names.put(id,name.toString())!=null)throw new AssertionError("Invalid vanilla registry ID: "+id);
            }
        }
        StringBuilder result=new StringBuilder("# Minecraft 1.12.2 vanilla Block.REGISTRY: numeric ID\\tregistry name\\t16 canonical metadata values (-1 unsupported)\n# Generated by exportLegacyVanillaBlockManifest; verify with testLegacyVanillaBlockManifest.\n");
        int normalized=0,invalid=0;
        for(Map.Entry<Integer,String> entry:names.entrySet()){
            result.append(entry.getKey()).append('\t').append(entry.getValue()).append('\t');
            Block block=Block.getBlockById(entry.getKey());
            for(int metadata=0;metadata<16;metadata++){
                if(metadata!=0)result.append(',');
                net.minecraft.block.state.IBlockState state;
                try{state=block.getStateFromMeta(metadata);}
                catch(RuntimeException unsupported){result.append(-1);invalid++;continue;}
                int canonical=block.getMetaFromState(state);
                if(canonical<0||canonical>15||!state.equals(block.getStateFromMeta(canonical)))throw new AssertionError("Non-reconstructible metadata: "+entry.getValue()+"@"+metadata);
                if(canonical!=metadata)normalized++;
                result.append(canonical);
            }
            result.append('\n');
        }
        byte[] expected=result.toString().getBytes(StandardCharsets.UTF_8);Path path=Paths.get(args[0]);
        if(args.length==2&&"--write".equals(args[1])){Files.createDirectories(path.getParent());Files.write(path,expected);}
        else if(!Arrays.equals(expected,Files.readAllBytes(path)))throw new AssertionError("Legacy vanilla block manifest drift; regenerate from actual 1.12.2 registry");
        if(normalized!=2263||invalid!=151)throw new AssertionError("Unexpected legacy normalization shape: "+normalized+"/"+invalid);
        if(names.size()!=254||!"minecraft:wooden_door".equals(names.get(64))||!"minecraft:air".equals(names.get(0)))throw new AssertionError("Unexpected vanilla registry shape: "+names.size());
        System.out.println("PASS: actual 1.12.2 vanilla block registry manifest "+names.size()+" entries; "+normalized+" normalized, "+invalid+" unsupported slots; numeric block IDs distinct from item IDs");
    }
}
